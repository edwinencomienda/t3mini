// bun run compile [--all]: builds the app (vite build), lists the page files so they're embedded,
// and compiles the t3mini binary into dist/bin: for this machine, or with --all also for Linux
// (x64, arm64) and both Macs. See README → Install.
import { execFileSync } from 'node:child_process'
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'

const root = join(import.meta.dir, '..')
const run = (command: string, args: string[]) =>
  execFileSync(command, args, { cwd: root, stdio: 'inherit' })

run('bun', ['run', 'build'])

// dist/client-files.ts: every page file by URL path, imported as a file so `bun build --compile`
// embeds it as-is (plain .js entrypoints would be compiled as code instead).
const client = join(root, 'dist', 'client')
const files: string[] = []
const walk = (folder: string) => {
  for (const entry of readdirSync(folder, { withFileTypes: true })) {
    const path = join(folder, entry.name)
    if (entry.isDirectory()) walk(path)
    else files.push(path)
  }
}
walk(client)
files.sort()
writeFileSync(
  join(root, 'dist', 'client-files.ts'),
  [
    '// Generated by cli/compile.ts: the page files, embedded in the t3mini binary.',
    ...files.map(
      (file, index) =>
        `import f${index} from ${JSON.stringify(`./client/${relative(client, file)}`)} with { type: 'file' }`,
    ),
    'export default {',
    ...files.map((file, index) => `  ${JSON.stringify(`/${relative(client, file)}`)}: f${index},`),
    '} as Record<string, string>',
    '',
  ].join('\n'),
)

const targets = process.argv.includes('--all')
  ? ['bun-darwin-arm64', 'bun-darwin-x64', 'bun-linux-x64', 'bun-linux-arm64']
  : [undefined]
mkdirSync(join(root, 'dist', 'bin'), { recursive: true })
for (const target of targets) {
  const outfile = join(root, 'dist', 'bin', target ? `t3mini-${target.slice(4)}` : 't3mini')
  run('bun', [
    'build',
    '--compile',
    '--minify',
    // Settings come from ~/.t3-mini/.env (see cli/t3mini.ts), never a stray .env or bunfig.toml
    // in whatever folder the binary is started from.
    '--no-compile-autoload-dotenv',
    '--no-compile-autoload-bunfig',
    // Playwright's optional Firefox (BiDi) support; t3 mini drives Chromium browsers over CDP.
    '--external',
    'chromium-bidi/*',
    ...(target ? [`--target=${target}`] : []),
    'cli/t3mini.ts',
    '--outfile',
    outfile,
  ])
  console.log(`→ ${relative(root, outfile)}`)
}
